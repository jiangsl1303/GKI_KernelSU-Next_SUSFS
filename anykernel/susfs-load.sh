#!/system/bin/sh
# susfs-load.sh -- load the KernelSU-Next SUSFS LKM on an already-booted
# device, and optionally install a boot-time hook.
#
# Usage (as root, from adb shell or a terminal on the device):
#   sh susfs-load.sh                     # load once, right now
#   sh susfs-load.sh /path/to/x.ko       # load a specific module file
#   sh susfs-load.sh --install           # also hook it into boot (see below)
#
# What --install does: writes /data/adb/ksu/susfs-autoload.sh, which the
# KernelSU-Next manager's late-load / service stage runs on every boot.
# Remove it with: rm -f /data/adb/ksu/susfs-autoload.sh

MODULE_DEFAULT=/data/adb/ksu/susfs_guard_lkm.ko
KSUD=$(command -v ksud || echo /data/adb/ksu/bin/ksud)

find_module() {
	m="$1"
	[ -n "$m" ] || for m in "$MODULE_DEFAULT" /sdcard/susfs_guard_lkm.ko \
	                       /data/local/tmp/susfs_guard_lkm.ko; do
		[ -f "$m" ] && break
	done
	echo "$m"
}

load_once() {
	m=$(find_module "$1")
	[ -f "$m" ] || { echo "module not found (looked at $MODULE_DEFAULT)"; exit 1; }
	if [ -e /proc/susfs_kstat ]; then
		echo "SUSFS already loaded:"; cat /proc/susfs_kstat 2>/dev/null; exit 0
	fi
	"$KSUD" insmod "$m" && echo "SUSFS loaded: $m"
	[ -e /proc/susfs_kstat ] && { echo "verified: /proc/susfs_kstat exists"; exit 0; }
	echo "insmod reported success but /proc/susfs_kstat is missing" >&2
	exit 1
}

install_hook() {
	m=$(find_module "$1")
	cat >/data/adb/ksu/susfs-autoload.sh <<EOF
#!/system/bin/sh
# Generated by susfs-load.sh --install. Loads the SUSFS LKM late in boot.
MOD=$m
[ -e /proc/susfs_kstat ] && exit 0
[ -f "\$MOD" ] && $KSUD insmod "\$MOD"
EOF
	chmod 0755 /data/adb/ksu/susfs-autoload.sh
	echo "installed /data/adb/ksu/susfs-autoload.sh (module: $m)"
	echo "note: KernelSU-Next runs late-load scripts from /data/adb/ksu;"
	echo "      if your build does not, run 'sh susfs-load.sh' once per boot."
}

case "${1:-}" in
	--install) install_hook "$2" ;;
	"")         load_once "" ;;
	*)          load_once "$1" ;;
esac
